"""Destructive synthetic checks ONLY on a freshly provisioned labelled N19 lab."""
import json
import subprocess
from pathlib import Path
import sys
from n19_lab import load,worker,check,sql,ROOT
from n19_controls_acceptance import prove


def cli_checks(state, lab):
    targets=json.loads(worker(lab,"from pathlib import Path;print(Path('/cv/synthetic-targets.json').read_text())").stdout)
    def invoke(action,target,extra=()):
        args=[arg for k,v in target.items() for arg in ['--'+k.replace('_','-'),v]]
        r=subprocess.run([sys.executable,str(ROOT/'docker/n19_delete.py'),action,'--state',str(state),*args,*extra],capture_output=True,text=True)
        assert r.returncode==0,'cli_check_failed'
        return json.loads(r.stdout)
    assert invoke('status',targets[0])['state']=='complete'
    # UUID was generated by the fresh fixture; never interpolate untrusted SQL.
    from uuid import UUID
    upload=str(UUID(targets[0]['upload_id']))
    digest=sql(lab,"SELECT plan_digest FROM submission_deletions WHERE upload_id='"+upload+"';")
    assert invoke('execute',targets[0],['--confirm-exact-submission','--expect-digest',digest])['state']=='complete'
    assert len(invoke('preview',targets[2])['digest'])==64
    print('PASS: 3 administrative CLI checks')


def main(state):
    lab=load(state)
    # seed() requires zero recruiters and exact new schema: refuses a used lab.
    worker(lab,"import asyncio,sys;sys.path.insert(0,'tests');from n19_deletion_scenarios import seed;asyncio.run(seed())",uid=10001)
    prove(state)
    check(lab)
    result=worker(lab,"import asyncio,sys;sys.path.insert(0,'tests');from n19_deletion_scenarios import scenarios;asyncio.run(scenarios())")
    print(result.stdout.strip())
    cli_checks(state,lab)
    check(lab)


if __name__=='__main__':
    try:main(Path(sys.argv[1]))
    except Exception:
        print('Acceptance failed; retain lab and private diagnostics. No cleanup performed.')
        raise SystemExit(1) from None
